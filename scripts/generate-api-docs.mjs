/** Build the API reference from the same declarations checked by docs:check. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { publicAPI, root } from './api-surface.mjs';
const publicEntries = publicAPI();
const publicKeys = new Set(publicEntries.map(entry => `${entry.file}:${entry.line}:${entry.name}`));
for (const includeInternal of [false, true]) {
let output = '# '+(includeInternal ? 'Internal' : 'Public')+' API reference\n\nGenerated by `npm run docs:build` from the TypeScript declarations.\n';
let file;
for (const entry of includeInternal ? publicAPI({includeInternal: true}).filter(entry => !publicKeys.has(`${entry.file}:${entry.line}:${entry.name}`)) : publicEntries) {
    if (entry.file !== file) {
        file = entry.file;
        output += `\n## ${file}\n`;
    }
    output += `\n### ${entry.name}\n\n${entry.description}\n\n[Source](../../${entry.file}#L${entry.line})\n\n\`\`\`typescript\n${entry.signature}\n\`\`\`\n`;
    const tags = entry.tags.filter(tag => ['param', 'returns', 'throws', 'deprecated', 'example'].includes(tag.name));
    for (const tag of tags) output += `\n- **@${tag.name}${tag.parameter ? ` ${tag.parameter}` : ''}** ${tag.text.replace(/\n/g, ' ')}\n`;
}
mkdirSync(join(root, 'docs', 'api'), {recursive: true});
writeFileSync(join(root, 'docs', 'api', includeInternal ? 'internal.md' : 'reference.md'), output);
console.log('Generated '+(includeInternal ? 'docs/api/internal.md' : 'docs/api/reference.md'));
}
